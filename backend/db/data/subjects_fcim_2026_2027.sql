-- Subjects of FCIM, licență years I-IV, 2026/2027: one row per subject and language, tagged with the clusters
-- (speciality within a year) it is taught to. A subject several specialities share is one row with all their
-- clusters (Analiza matematică 1 is one subject for AI, CR, EA, IA, IBM, MN, R, SD, SI and TI).
--
-- Sources: the study plans in "planuri de invatamant" and the timetables ORARE/ANUL-1..4.pdf of this autumn.
--   year I   (groups *-26x): AI-26, CR-26, EA-26, FAF-26, IA-26, IBM-26, MN-26, R-26, SD-26, SI-26, TI-26 (semesters 1, 2)
--   year II  (groups *-25x): the *-25 plans (semesters 3, 4). IA and SD spend semester 3 in internship.
--   year III (groups *-24x): the *-23-24 plans, IA-24, SD-24, RM-23-24 (semesters 5, 6)
--   year IV  (groups *-23x): the *-23-24 plans, RM-23-24 (semester 7; FAF also semester 8)
--   FI (TI taught in French, FI-241 and FI-231) follows TI-23-24.
--   EA-26 and MN-26 year I are scanned pages, read by eye (MN-26 semester 2 prints 9 credits for Matematica
--   discretă and Probabilitate…; the semester's total of 30 needs 4 and 5).
--
-- Rows
--   semester = the semester of the year (1 autumn, 2 spring); year = the year of study.
--   Pairs a week = hours / 30 (15 weeks, 2 hours a pair), to the nearest 0.5. The autumn of year III in the
--     *-23-24 plans has 12 weeks of classes (4 weeks of internship): hours / 24, which matches the timetable.
--   Lecture = Curs; seminar = Seminar + Lucrări practice; lab = Lucrări de laborator. Proiect hours are not
--     stored (no column for them), so a project-only subject (Proiecte IoT, Aplicație client-server…) has no pairs.
--   Assessment: Midterm 1, Midterm 2 and Exam for every subject; Educație fizică ends with a test (no exam) and is
--     kept at the edge of the day.
--   Integrarea (economică) europeană: EA-25, IBM-25 and MN-25 list its 30 hours as practical work; it is a lecture
--     everywhere else and in the timetable, so it is a lecture here too.
--   Optional pairs (U.A.x / U.A.y, S.A.x / S.A.y) are one subject per alternative.
--   Left out: internships, the bachelor's thesis, free electives (L.A.*) and semesters with internships only.
--
-- Languages (a subject is offered to the groups of its language)
--   ro  the Romanian groups;
--   ru  the Russian groups. Year I: the groups that take "Limba română pentru alolingvi" (AI-262/263, CR-263,
--       EA-262, IBM-262, MN-262, R-262/264, IA-263/264, SD-263, SI-267..269, TI-264/265). Years II-IV: the
--       separate Russian streams of the timetable (II: TI-255/256 + SI-254..256 and CR-253 + EA-251 + IBM-252 +
--       R-252; III: TI-245/246 + SI-243; IV: TI-235/236 + SI-232). "Limba română pentru alolingvi" is only for them.
--   en  FAF (Inginerie software is taught in English);
--   fr  FI.
--   The same subject in two languages is two rows with the same code.
--
-- Codes: an abbreviation of the name (AM1, ALGA, POO, SO). The same name with other hours, credits or in another
--   year is another subject: the one most specialities share keeps the plain code, the others add their
--   specialities (FIZ-CR, SO-IA-SD) or, for the main one of a later year, the year (SSM-1, ANT-2).
--
-- Clusters: each row is tagged with the cluster of every speciality it is for in that year ("TI · Year 1"),
--   made here if the groups that make them are not loaded yet.
--
-- Safe to run again: existing subjects (same code, cycle, faculty and language) and tags are skipped.

